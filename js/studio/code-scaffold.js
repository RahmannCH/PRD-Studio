/* PRD-to-Code Scaffold Generator untuk PRD Studio.
   Menghasilkan scaffold proyek nyata (package.json, source stubs, route stubs,
   test stubs, README) berdasarkan spec PRD. Bukan hanya markdown, tapi kode
   yang bisa langsung dijalankan.
   ES5 murni tanpa bundler. */
(function () {
  function clean(s) { return String(s || '').replace(/\s+/g, ' ').trim(); }

  function slugify(s) {
    return String(s || 'produk').toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-+|-+$/g, '').slice(0, 40) || 'produk';
  }

  function generatePackageJson(spec, projectName) {
    var slug = slugify(projectName);
    var stack = (spec && spec.meta && spec.meta.stackPref) || 'HTML CSS JS vanilla';
    var isNode = /node|hono|fastify|express|next|react|vite|tanstack/i.test(stack);
    var isPython = /python|fastapi|django/i.test(stack);
    var pkg = {
      name: slug,
      version: '0.1.0',
      description: (spec && spec.summary && spec.summary.oneLiner) || projectName,
      main: isNode ? 'src/index.js' : 'main.py',
      scripts: {}
    };
    if (isNode) {
      pkg.scripts = { start: 'node src/index.js', dev: 'node --watch src/index.js', test: 'node --test', lint: 'eslint src/' };
      pkg.dependencies = {};
      pkg.devDependencies = { eslint: '^8.0.0' };
      if (/react/i.test(stack)) { pkg.dependencies.react = '^18.0.0'; pkg.dependencies['react-dom'] = '^18.0.0'; }
      if (/next/i.test(stack)) { pkg.dependencies.next = '^14.0.0'; }
      if (/hono/i.test(stack)) { pkg.dependencies.hono = '^4.0.0'; }
      if (/express/i.test(stack)) { pkg.dependencies.express = '^4.18.0'; }
    } else if (isPython) {
      pkg = null; // Python uses requirements.txt
    }
    if (isPython) {
      return '# requirements.txt\nfastapi>=0.100.0\nuvicorn>=0.23.0\nsqlalchemy>=2.0.0\npydantic>=2.0.0\npytest>=7.0.0\n';
    }
    return JSON.stringify(pkg, null, 2);
  }

  function generateIndexJs(spec, projectName) {
    var endpoints = (spec && spec.endpoints) || [];
    var lines = [];
    lines.push('// ' + projectName + ' - Entry point');
    lines.push('// Generated by PRD Studio');
    lines.push('');
    lines.push("const http = require('http');");
    lines.push('');
    lines.push('const PORT = process.env.PORT || 3000;');
    lines.push('');
    lines.push('const server = http.createServer(function (req, res) {');
    lines.push("  res.setHeader('Content-Type', 'application/json');");
    lines.push("  if (req.url === '/health') {");
    lines.push("    res.writeHead(200);");
    lines.push("    res.end(JSON.stringify({ status: 'ok', project: '" + projectName.replace(/'/g, "\\'") + "' }));");
    lines.push('    return;');
    lines.push('  }');
    endpoints.forEach(function (ep) {
      var method = (ep.m || 'GET').toUpperCase();
      var path = ep.p || '/';
      lines.push("  if (req.url === '" + path + "' && req.method === '" + method + "') {");
      lines.push("    res.writeHead(200);");
      lines.push("    res.end(JSON.stringify({ message: '" + method + " " + path + " OK' }));");
      lines.push('    return;');
      lines.push('  }');
    });
    lines.push("  res.writeHead(404);");
    lines.push("  res.end(JSON.stringify({ error: 'Not found' }));");
    lines.push('});');
    lines.push('');
    lines.push('server.listen(PORT, function () {');
    lines.push("  console.log('Server running on port ' + PORT);");
    lines.push('});');
    lines.push('');
    lines.push('module.exports = server;');
    return lines.join('\n');
  }

  function generateEntityModel(entity) {
    var lines = [];
    var label = (entity && entity.label) || 'Entity';
    var fields = (entity && entity.fields) || [];
    lines.push('// ' + label + ' model');
    lines.push('function ' + label + '(data) {');
    lines.push('  data = data || {};');
    fields.forEach(function (f) {
      lines.push('  this.' + f.n + ' = data.' + f.n + ' !== undefined ? data.' + f.n + ' : ' + (f.t === 'string' ? "''" : (f.t === 'int' ? '0' : (f.t === 'bool' ? 'false' : 'null'))) + ';');
    });
    lines.push('}');
    lines.push('');
    lines.push('module.exports = ' + label + ';');
    return lines.join('\n');
  }

  function generateTestFile(spec, projectName) {
    var lines = [];
    lines.push('// Tests for ' + projectName);
    lines.push("const assert = require('assert');");
    lines.push('');
    lines.push("describe('" + projectName + "', function () {");
    lines.push("  it('should start server', function () {");
    lines.push("    assert.ok(true);");
    lines.push('  });');
    var entities = (spec && spec.entities) || [];
    entities.forEach(function (e) {
      lines.push("  it('should create " + e.label + "', function () {");
      lines.push("    assert.ok(true);");
      lines.push('  });');
    });
    lines.push('});');
    return lines.join('\n');
  }

  function generateReadme(spec, projectName) {
    var lines = [];
    lines.push('# ' + projectName);
    lines.push('');
    lines.push((spec && spec.summary && spec.summary.oneLiner) || 'Project generated by PRD Studio');
    lines.push('');
    lines.push('## Setup');
    lines.push('```bash');
    lines.push('npm install');
    lines.push('npm start');
    lines.push('```');
    lines.push('');
    lines.push('## Test');
    lines.push('```bash');
    lines.push('npm test');
    lines.push('```');
    lines.push('');
    lines.push('## Structure');
    lines.push('- `src/` - Source code');
    lines.push('- `src/models/` - Data models');
    lines.push('- `src/routes/` - API routes');
    lines.push('- `tests/` - Test files');
    lines.push('');
    lines.push('## Generated by PRD Studio');
    return lines.join('\n');
  }

  function generateScaffold(spec, projectName) {
    spec = spec || {};
    projectName = projectName || (spec.meta && spec.meta.productName) || 'produk';
    var slug = slugify(projectName);
    var files = [];

    // package.json / requirements.txt
    files.push({ path: 'package.json', content: generatePackageJson(spec, projectName), type: 'json' });

    // index.js
    files.push({ path: 'src/index.js', content: generateIndexJs(spec, projectName), type: 'javascript' });

    // Entity models
    (spec.entities || []).forEach(function (e) {
      files.push({ path: 'src/models/' + e.label.toLowerCase() + '.js', content: generateEntityModel(e), type: 'javascript' });
    });

    // Test file
    files.push({ path: 'tests/' + slug + '.test.js', content: generateTestFile(spec, projectName), type: 'javascript' });

    // README
    files.push({ path: 'README.md', content: generateReadme(spec, projectName), type: 'markdown' });

    // .gitignore
    files.push({ path: '.gitignore', content: 'node_modules/\n.env\n*.log\n', type: 'text' });

    // .env.example
    var envVars = ['PORT=3000', 'NODE_ENV=development'];
    files.push({ path: '.env.example', content: envVars.join('\n') + '\n', type: 'text' });

    return {
      projectName: projectName,
      slug: slug,
      fileCount: files.length,
      files: files
    };
  }

  function scaffoldToMarkdown(scaffold) {
    scaffold = scaffold || {};
    var lines = [];
    lines.push('# Code Scaffold: ' + (scaffold.projectName || 'Produk'));
    lines.push('');
    lines.push('**Total file:** ' + (scaffold.fileCount || 0));
    lines.push('');
    (scaffold.files || []).forEach(function (f) {
      lines.push('## ' + f.path);
      lines.push('```' + (f.type === 'javascript' ? 'js' : (f.type === 'json' ? 'json' : (f.type === 'markdown' ? 'md' : ''))));
      lines.push(f.content);
      lines.push('```');
      lines.push('');
    });
    return lines.join('\n');
  }

  window.CodeScaffold = {
    generatePackageJson: generatePackageJson,
    generateIndexJs: generateIndexJs,
    generateEntityModel: generateEntityModel,
    generateTestFile: generateTestFile,
    generateReadme: generateReadme,
    generateScaffold: generateScaffold,
    scaffoldToMarkdown: scaffoldToMarkdown
  };
})();
